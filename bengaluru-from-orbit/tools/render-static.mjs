// Renders design-source/ThreeColor.dc.html (the Claude Design canvas source) into
// plain, framework-free HTML at ../index.html, and extracts the Earth fragment
// shader into ../shaders/earth.frag + ../js/earth-shader.js.
//
//   node tools/render-static.mjs
//
// The design source is the single source of truth for markup, copy and inline
// styles. Interactive hooks (data-*) are injected so js/page.js can drive the
// sound toggle, layer chips, heat-map cells and simulation sliders without a framework.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const src = fs.readFileSync(path.join(root, 'design-source/ThreeColor.dc.html'), 'utf8');

// ---- 1. pull the template, helmet styles and component class ----
const xdc = src.slice(src.indexOf('<x-dc>') + 6, src.indexOf('</x-dc>'));
const helmetStyle = xdc.match(/<style>([\s\S]*?)<\/style>/)[1];
let tpl = xdc.slice(xdc.indexOf('</helmet>') + 9).trim();
const cls = src.match(/data-dc-script[^>]*>([\s\S]*?)<\/script>/)[1];

// ---- 2. evaluate renderVals() with a stub runtime ----
class DCLogic { constructor() { this.props = {}; } setState() {} forceUpdate() {} }
const Component = new Function('DCLogic', 'window', 'document', cls + '\nreturn Component;')(DCLogic, {}, {});
const comp = new Component();
comp.props = {};
const vals = comp.renderVals();

// ---- 3. inject data-* hooks for page.js ----
const rep = (a, b) => { if (!tpl.includes(a)) throw new Error('hook not found: ' + a); tpl = tpl.split(a).join(b); };
rep(' ref="{{setCv}}"', ' id="earth"');
rep('onClick="{{toggleSound}}"', 'data-action="sound"');
rep('</span>{{soundText}}', '</span><span data-bind="soundText">{{soundText}}</span>');
['eqA', 'eqB', 'eqC'].forEach((k) => rep(';animation:{{' + k + '}}"', ';animation:{{' + k + '}}" data-eq="' + k + '"'));
rep('onClick="{{c.pick}}"', 'data-chip="{{c.key}}"');
rep('<div aria-hidden="true" style="display:grid;grid-template-columns:repeat(24, minmax(0, 1fr));gap:3px">', '<div aria-hidden="true" data-cells="1" style="display:grid;grid-template-columns:repeat(24, minmax(0, 1fr));gap:3px">');
['chipLabel', 'chipValue', 'rampLo', 'rampHi', 'simDelta'].forEach((k) => rep('{{' + k + '}}', '<span data-bind="' + k + '">{{' + k + '}}</span>'));
rep('background:{{rampCss}}"', 'background:{{rampCss}}" data-ramp="1"');
rep('<span style="font-weight:500">{{s.display}}</span>', '<span style="font-weight:500" data-display="{{s.key}}">{{s.display}}</span>');
rep('width:{{s.pct}};border-radius:2px;background:linear-gradient(90deg,#7FE0F0,#5B8CFF,#9A86B8)"', 'width:{{s.pct}};border-radius:2px;background:linear-gradient(90deg,#7FE0F0,#5B8CFF,#9A86B8)" data-fill="{{s.key}}"');
rep('border:2px solid #F2F2F2;box-sizing:border-box"></span>', 'border:2px solid #F2F2F2;box-sizing:border-box" data-thumb="{{s.key}}"></span>');
rep('onChange="{{s.onChange}}"', 'data-slider="{{s.key}}"');
vals.chips.forEach((c, i) => { c.key = ['air', 'lst', 'rain', 'rh', 'wind'][i]; });
vals.sliders.forEach((s) => { s.key = s.id.replace('sim-', ''); });

// ---- 4. expand <sc-for> and {{holes}} ----
const esc = (v) => String(v).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const look = (scope, p) => p.split('.').reduce((o, k) => (o == null ? o : o[k]), scope);
const holes = (s, scope) => s.replace(/\{\{\s*([\w.$]+)\s*\}\}/g, (_, p) => { const v = look(scope, p); if (v === undefined) throw new Error('missing value ' + p); return esc(v); });
tpl = tpl.replace(/<sc-for list="\{\{\s*(\w+)\s*\}\}" as="(\w+)"[^>]*>([\s\S]*?)<\/sc-for>/g, (_, list, as, body) =>
  vals[list].map((item, i) => holes(body, { ...vals, [as]: item, $index: i })).join(''));
tpl = holes(tpl, vals);
if (/\{\{|<sc-|onClick=|onChange=/.test(tpl)) throw new Error('unexpanded template syntax left');

// ---- 5. write index.html ----
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Bengaluru From Orbit</title>
<meta name="description" content="Temperature, rainfall, humidity and wind over Bengaluru — from NASA satellites and models.">
<link rel="preload" href="assets/textures/earth_day_8k.jpg" as="image" crossorigin="anonymous">
<link rel="stylesheet" href="css/fonts.css">
<style>${helmetStyle.replace(/\n/g, '\n')}</style>
</head>
<body>
<!-- GENERATED by tools/render-static.mjs from design-source/ThreeColor.dc.html — edit the source, then re-run. -->
${tpl}
<script src="js/earth-shader.js"></script>
<script src="js/earth-globe.js"></script>
<script src="js/space-ambience.js"></script>
<script src="js/page.js"></script>
</body>
</html>
`;
fs.writeFileSync(path.join(root, 'index.html'), html);

// ---- 6. extract the shader ----
const fsLines = cls.match(/FS = \[([\s\S]*?)\]\.join/)[1];
const glsl = new Function('return [' + fsLines + '].join("\\n")')();
fs.writeFileSync(path.join(root, 'shaders/earth.frag'), glsl + '\n');
fs.writeFileSync(path.join(root, 'js/earth-shader.js'),
  '// GENERATED from design-source/ThreeColor.dc.html by tools/render-static.mjs (also in shaders/earth.frag).\n' +
  'window.EARTH_FRAGMENT_SHADER = ' + JSON.stringify(glsl) + ';\n' +
  'window.EARTH_VERTEX_SHADER = "#version 300 es\\nin vec2 p;void main(){gl_Position=vec4(p,0.,1.);}";\n');
console.log('index.html written:', html.length, 'chars; shader', glsl.length, 'chars');
